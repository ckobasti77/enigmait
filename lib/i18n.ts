export const serbianToEnglish = Object.fromEntries(
  englishToSerbianEntries.map(([english, serbian]) => [
    normalizeText(serbian),
    english,
  ])
) as Record<string, string>;

const preserveOuterWhitespace = (original: string, replacement: string) => {
  const leading = original.match(/^\s*/)?.[0] ?? "";
  const trailing = original.match(/\s*$/)?.[0] ?? "";
  return `${leading}${replacement}${trailing}`;
};

const translateDynamicPattern = (value: string, locale: Locale) => {
  const normalized = normalizeText(value);

  if (locale === "sr") {
    const copyright = normalized.match(/^© (\d{4}) Enigma Digital\. All rights reserved\.$/);
    if (copyright) {
      return preserveOuterWhitespace(
        value,
        `© ${copyright[1]} Enigma Digital. Sva prava zadržana.`
      );
    }
  }

  const srCopyright = normalized.match(/^© (\d{4}) Enigma Digital\. Sva prava zadržana\.$/);
  if (locale === "en" && srCopyright) {
    return preserveOuterWhitespace(
      value,
      `© ${srCopyright[1]} Enigma Digital. All rights reserved.`
    );
  }

  return null;
};

export const translateText = (value: string, locale: Locale) => {
  const dynamic = translateDynamicPattern(value, locale);
  if (dynamic) return dynamic;

  const normalized = normalizeText(value);
  if (!normalized) return value;

  const lookup = locale === "sr" ? englishToSerbian : serbianToEnglish;
  const translated = lookup[normalized];

  if (!translated) {
    return value;
  }

  return preserveOuterWhitespace(value, translated);
};

export const isLocale = (value: string | null): value is Locale =>
  value === "sr" || value === "en";
